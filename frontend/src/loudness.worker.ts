export type LoudnessMessage =
  | { kind: 'start'; frames: number; channels: number; sampleRate: number }
  | { kind: 'samples'; offset: number; samples: Float32Array[] }
  | { kind: 'finish' };
export type LoudnessReply =
  | { kind: 'ready'; license?: string }
  | { kind: 'result'; integratedLufs: number; peakDbfs: number }
  | { kind: 'error'; error: string };

interface NativeAnalyzer extends WebAssembly.Exports {
  memory: WebAssembly.Memory;
  __wbindgen_malloc(bytes: number): number;
  ebur128_integrated_mono(rate: number, pointer: number, frames: number): number;
  ebur128_integrated_stereo(rate: number, left: number, leftFrames: number, right: number, rightFrames: number): number;
}

const scope = globalThis as unknown as {
  onmessage: ((event: MessageEvent<LoudnessMessage>) => void) | null;
  postMessage(message: LoudnessReply): void;
  close(): void;
};
let native: NativeAnalyzer | undefined;
let configuration: Extract<LoudnessMessage, { kind: 'start' }> | undefined;
let pointers: number[] = [];
let received = 0;
let peak = 0;
let busy = false;

async function handle(message: LoudnessMessage): Promise<LoudnessReply> {
  if (message.kind === 'start') {
    if (configuration || !Number.isSafeInteger(message.frames) || message.frames <= 0 ||
      ![1, 2].includes(message.channels) || message.frames * message.channels * 4 > 128 * 1024 * 1024 ||
      !Number.isInteger(message.sampleRate) || message.sampleRate < 8000 || message.sampleRate > 96000 ||
      message.frames / message.sampleRate > 360) throw new Error('audio_memory_limit');
    configuration = message;
    if (!wasmUrl.startsWith('data:application/wasm;base64,')) throw new Error('loudness_unavailable');
    const bytes = Uint8Array.from(atob(wasmUrl.slice(wasmUrl.indexOf(',') + 1)), character => character.charCodeAt(0));
    const panic = () => { throw new Error('loudness_unavailable'); };
    const instance = await WebAssembly.instantiate(bytes, { './ebur128_wasm_bg.js': {
      __wbg_new_693216e109162396: panic,
      __wbg_stack_0ddaca5d1abfb52f: panic,
      __wbg_error_09919627ac0992f5: panic,
      __wbindgen_object_drop_ref: panic,
    } });
    native = instance.instance.exports as NativeAnalyzer;
    pointers = Array.from({ length: message.channels }, () => native!.__wbindgen_malloc(message.frames * 4));
    return { kind: 'ready', license: `${license}\n${nativeLicense}` };
  }
  if (!native || !configuration) throw new Error('invalid_audio');
  if (message.kind === 'samples') {
    const length = message.samples?.[0]?.length;
    if (message.offset !== received || !length || length > 32768 || received + length > configuration.frames ||
      message.samples.length !== configuration.channels) throw new Error('invalid_audio');
    for (let channel = 0; channel < configuration.channels; channel++) {
      const samples = message.samples[channel];
      if (!(samples instanceof Float32Array) || samples.length !== length) throw new Error('invalid_audio');
      for (const sample of samples) {
        if (!Number.isFinite(sample)) throw new Error('invalid_audio');
        peak = Math.max(peak, Math.abs(sample));
      }
      new Float32Array(native.memory.buffer, pointers[channel] + received * 4, length).set(samples);
    }
    received += length;
    return { kind: 'ready' };
  }
  if (message.kind !== 'finish' || received !== configuration.frames) throw new Error('invalid_audio');
  if (peak === 0) throw new Error('loudness_no_signal');
  const { sampleRate, frames, channels } = configuration;
  const integratedLufs = channels === 1 ? native.ebur128_integrated_mono(sampleRate, pointers[0], frames) :
    native.ebur128_integrated_stereo(sampleRate, pointers[0], frames, pointers[1], frames);
  if (!Number.isFinite(integratedLufs)) throw new Error('loudness_no_signal');
  return { kind: 'result', integratedLufs, peakDbfs: 20 * Math.log10(peak) };
}

scope.onmessage = event => {
  if (busy) { scope.postMessage({ kind: 'error', error: 'invalid_audio' }); scope.close(); return; }
  busy = true;
  void (async () => {
    let finished = event.data?.kind === 'finish';
    try { scope.postMessage(await handle(event.data)); }
    catch (error) {
      finished = true;
      const code = error instanceof Error && ['invalid_audio', 'audio_memory_limit', 'loudness_no_signal'].includes(error.message) ?
        error.message : 'loudness_unavailable';
      scope.postMessage({ kind: 'error', error: code });
    } finally {
      busy = false;
      if (finished) {
        native = undefined;
        pointers = [];
        configuration = undefined;
        scope.close();
      }
    }
  })();
};